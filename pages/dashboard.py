import numpy as np
import pandas as pd
import streamlit as st
import json

from app_backend.prompting import *
from app_backend.streamlit import *

# Backgrounf for the app
background = """
<style>
[data-testid="stMain"] {
background: linear-gradient(to bottom, #004e92, #000428); /* W3C, IE 10+/ Edge, Firefox 16+, Chrome 26+, Opera 12+, Safari 7+ */
}
</style>
"""

st.markdown(background, unsafe_allow_html=True)


if 'go_back' not in st.session_state: # This will execute if the button to go back to the "streamlit_code" has not been pressed
    ai_answer_dash = st.session_state.ai_dashboard # Loading the dashboard specs generated by Claude 

    st.title('Dashboard', text_alignment='center') 
    st.divider()

    st.subheader('Answer to your question:')
    # Displaying the interpretation and insights obtained from the query output
    insights = ai_answer_dash['interpretation'].replace("$", "\\$") # Loading the interpretation and replacing the "$" sign to not confuse with LateX formatting
    st.write_stream(stream_ai_response(insights)) # Writing the interpretation from the result as a stream of words

    # Displaying the metrics list
    metrics_list = ai_answer_dash['metrics'] # Loading the metrics list generated by Claude
    n_cols = len(metrics_list) # Counting how many metrics where calculated, which will be also the number of columns
    # Using the same number of columns as the number of metrics
    if n_cols == 1:
        st.metric(metrics_list[0]['name'], metrics_list[0]['value']) 
    elif n_cols == 2:
        col1, col2 = st.columns(2)
        col1.metric(metrics_list[0]['name'], metrics_list[0]['value'])
        col2.metric(metrics_list[1]['name'], metrics_list[1]['value'])    
    elif n_cols == 3:
        col1, col2, col3 = st.columns(3)
        col1.metric(metrics_list[0]['name'], metrics_list[0]['value'])
        col2.metric(metrics_list[1]['name'], metrics_list[1]['value'])
        col3.metric(metrics_list[2]['name'], metrics_list[2]['value'])

    ###### GRAPHING THE RESULT USING CLAUDE TO COLLECT INSIGHTS

    final_df = st.session_state.dataframe # Loading the final dataframe
    st.divider()

    graph_fig = build_graph(final_df, ai_answer_dash['chart']) # Creating the final graph for the dashboard, using Claude's generated specifications

    if graph_fig is not None:
        # Display Results in 3 Tabs 
        chart_tab, dataframe_tab, query_tab = st.tabs(["Chart", "Raw Data", "SQL Query"]) # Creating the 3 tabs that will display the chart, the DF and the SQL query
        chart_tab.altair_chart(graph_fig, width='stretch', theme=None)  # en Streamlit reciente: width='stretch'
    else:
        # Display Results 2 in Tabs 
        dataframe_tab, query_tab = st.tabs(["Raw Data", "SQL Query"]) # Creating only 2 tabs: the DF and the SQL query (since no chart was made here)

    dataframe_tab.dataframe(final_df, width='stretch') # Showing the final dataframe
    query_tab.code(st.session_state.generated_query, "sql") # Showing the generated sql query

    st.toast(f'Dashboard generated successfully!\nClaude token cost: ${round(token_cost(*st.session_state.tokens), 2)} USD', icon="🎉") # If everyting was executed correctly, an snowflake animation will be displayed on the screen!

else:
    # This will execute if the 'Ask another question' button is pressed
    del st.session_state.messages # Resetting 'messages', with the streamlit chat message history
    del st.session_state.generation_status # Resetting 'generation_status', that is used on the code logic on the other page
    del st.session_state.mode_disabled # Resetting 'mode_disabled', which disables or enables the claude selection mode
    del st.session_state.aclarations # Resetting 'aclarations', the dictionary with the user aclaration and aclaration question 
    del st.session_state.go_back # Resetting 'go_back', so that when the user comes back, the above code will be executed
    st.switch_page("streamlit_code.py")

col1, col2 = st.columns([3, 1]) # Using columns to display the button on the right bottom of the page
col2.button('Ask another question', type="primary", key='go_back') # Displaying button for going back to the "streamlit_code"